const fs = require("node:fs");
const path = require("node:path");
const {
  assertNonEmptyFile,
  collectAssetReferences,
  inlineAssetReferences,
  readArgument,
  readWebFile,
  replaceRequired,
  stripInlineBlocks,
  webDir,
  writeFileAtomic,
} = require("./build-helpers");

const outputPath = readArgument("--output", path.join(webDir, "monkey-no-fly-zone-standalone.html"));

const gamePath = readArgument("--game", path.join(webDir, "game.js"));
assertNonEmptyFile(gamePath, 32 * 1024, "Browser game bundle");

let gameSource = fs.readFileSync(gamePath, "utf8");
let stylesSource = readWebFile("styles.css");
let audioSource = readWebFile("audio.js");
let html = readWebFile("index.html");
const assetFiles = collectAssetReferences(gameSource, stylesSource, audioSource, html);

gameSource = inlineAssetReferences(gameSource, assetFiles);
stylesSource = inlineAssetReferences(stylesSource, assetFiles);
audioSource = inlineAssetReferences(audioSource, assetFiles);
html = inlineAssetReferences(html, assetFiles);

const escapeScript = (source) => source.replace(/<\/script/gi, "<\\/script");
html = replaceRequired(
  html,
  /<link rel="stylesheet" href="\.\/styles\.css(?:\?[^\"]+)?">/,
  `<style>\n${stylesSource}\n</style>`,
  "stylesheet link",
);
html = replaceRequired(
  html,
  /\s*<script src="\.\/audio\.js(?:\?[^\"]+)?"><\/script>/,
  `\n    <script>\n${escapeScript(audioSource)}\n    </script>`,
  "audio script",
);
html = replaceRequired(
  html,
  /\s*<script src="\.\/game\.js(?:\?[^\"]+)?"><\/script>/,
  `\n    <script>\n${escapeScript(gameSource)}\n    </script>`,
  "game script",
);
html = html.replace(
  "<title>Monkey See, Monkey Pew</title>",
  "<title>Monkey See, Monkey Pew - Standalone</title>"
);
html = [
  "<!-- Self-contained build generated by scripts/build-standalone.js -->",
  `<!-- Embedded assets: ${assetFiles.length ? assetFiles.join(", ") : "none"} -->`,
  html,
].join("\n");

if (/(?:\.\/)?assets\/[A-Za-z0-9._/-]+\.(?:avif|gif|jpe?g|m4a|mp3|ogg|png|svg|wav|webp)/i.test(html)) {
  throw new Error("Standalone output still contains a local media reference.");
}
const standaloneShell = stripInlineBlocks(html);
const unresolvedTag = standaloneShell.match(/<(?:link|script)\s+[^>\r\n]*(?:href|src)="\.\//i);
if (unresolvedTag) {
  const context = standaloneShell.slice(Math.max(0, unresolvedTag.index - 60), unresolvedTag.index + unresolvedTag[0].length + 80);
  throw new Error(`Standalone output still contains a local stylesheet or script reference near: ${JSON.stringify(context)}`);
}

writeFileAtomic(outputPath, html);
const bytes = assertNonEmptyFile(outputPath, 64 * 1024, "Standalone game");
console.log(`Built ${outputPath} (${(bytes / 1024 / 1024).toFixed(2)} MB) with ${assetFiles.length} embedded media assets.`);
