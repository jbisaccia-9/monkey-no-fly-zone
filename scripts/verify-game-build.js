function requireMatch(source, expression, message) {
  if (!expression.test(source)) throw new Error(message);
}

const indexPath = path.join(webDir, "index.html");
const bundlePath = readArgument("--bundle", path.join(webDir, "game.js"));
const standalonePath = readArgument("--standalone", path.join(webDir, "monkey-no-fly-zone-standalone.html"));

const index = fs.readFileSync(indexPath, "utf8");
for (const id of REQUIRED_IDS) {
  requireMatch(index, new RegExp(`\\bid=["']${id}["']`), `web/index.html is missing required DOM hook #${id}`);
}

const bundleSize = assertNonEmptyFile(bundlePath, 32 * 1024, "Browser game bundle");
const bundle = fs.readFileSync(bundlePath, "utf8");
requireMatch(bundle, /WebGLRenderer/, "Browser game bundle does not contain the Three.js renderer.");
if (/^\s*(?:import|export)\s/m.test(bundle)) throw new Error("Browser game bundle contains an unbundled ESM statement.");

const standaloneSize = assertNonEmptyFile(standalonePath, 64 * 1024, "Standalone game");
const standalone = fs.readFileSync(standalonePath, "utf8");
requireMatch(standalone, /Self-contained build generated by scripts\/build-standalone\.js/, "Standalone build marker is missing.");
requireMatch(standalone, /Embedded assets:/, "Standalone embedded-asset manifest is missing. Rebuild the standalone output.");
requireMatch(standalone, /<canvas\b[^>]*\bid=["']game["']/, "Standalone game canvas is missing.");
requireMatch(standalone, /data:image\/(?:avif|gif|jpeg|png|svg\+xml|webp);base64,/, "Standalone build does not contain an embedded image.");
requireMatch(standalone, /data:audio\/(?:mpeg|mp4|ogg|wav);base64,/, "Standalone build does not contain embedded character voices.");
if (/(?:\.\/)?assets\/[A-Za-z0-9._/-]+\.(?:avif|gif|jpe?g|m4a|mp3|ogg|png|svg|wav|webp)/i.test(standalone)) {
  throw new Error("Standalone build contains an unresolved local media reference.");
}
if (/<(?:link|script)\s+[^>\r\n]*(?:href|src)="\.\//i.test(stripInlineBlocks(standalone))) {
  throw new Error("Standalone build contains an unresolved local stylesheet or script reference.");
}

console.log(`Verified ${REQUIRED_IDS.length} DOM hooks, ${(bundleSize / 1024).toFixed(1)} KB bundle, and ${(standaloneSize / 1024 / 1024).toFixed(2)} MB standalone artifact.`);
